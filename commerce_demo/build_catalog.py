"""Rebuild the traceable local demo catalog using only the Python standard library."""
import csv
import hashlib
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
def build():
    directory = ROOT / 'data/raw/olist'
    products_path = directory / 'olist_products_dataset.csv'
    items_path = directory / 'olist_order_items_dataset.csv'
    with items_path.open(encoding='utf-8', newline='') as file:
        eligible = {row['product_id'] for row in csv.DictReader(file)}
    with products_path.open(encoding='utf-8', newline='') as file:
        products = sorted((row for row in csv.DictReader(file) if row['product_category_name'] and row['product_id'] in eligible), key=lambda row: row['product_id'])[:12]
    if len(products) != 12:
        raise ValueError('Twelve eligible source products required')
    catalog = [{'source': {'product_id': row['product_id'], 'product_category_name': row['product_category_name']}, 'display': {'title': f"{row['product_category_name'].replace('_', ' ').title()} / {row['product_id'][:6]}", 'description': 'Fictional demonstration item. No original name, description or photograph is available.', 'price_minor': 2500 + i * 750, 'provenance': 'manual_demo'}} for i, row in enumerate(products)]
    manifest = {path.name: hashlib.sha256(path.read_bytes()).hexdigest() for path in (products_path, items_path)}
    output = '// Generated by build_catalog.py. Original fields and fictional display fields are separate.\nexport const sourceChecksums = ' + json.dumps(manifest, sort_keys=True) + ';\nexport const catalog = ' + json.dumps(catalog, indent=2, ensure_ascii=True) + ';\n'
    (ROOT / 'commerce_demo/catalog.mjs').write_text(output, encoding='utf-8')
if __name__ == '__main__':
    build()
